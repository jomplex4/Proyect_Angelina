    fun topicName(id: String) = topics.firstOrNull { it.id == id }?.name ?: id
    fun byId(id: String) = all.firstOrNull { it.id == id }

    /** Simulacro: 30 preguntas repartidas entre todos los temas (por turnos) y luego mezcladas. */
    fun simulacro(seed: Long): List<String> {
        val rnd = Random(seed)
        val pools = topics.map { t -> all.filter { it.topic == t.id }.shuffled(rnd).toMutableList() }
        val pick = ArrayList<String>()
        while (pick.size < SIM_SIZE && pools.any { it.isNotEmpty() }) for (p in pools) if (pick.size < SIM_SIZE && p.isNotEmpty()) pick.add(p.removeAt(0).id)
        return pick.shuffled(rnd)
    }

