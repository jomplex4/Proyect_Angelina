@fig("x23_26")
def _(f):
    O = (512, 680); R = 130; r = 62
    f.disc(*O, R, 7); f.disc(*O, r, 6); f.ci(*O, R); f.ci(*O, r)
    d = math.radians(-50)  # dirección del punto de tangencia
    T = (O[0]+r*math.cos(d), O[1]+r*math.sin(d)); h = math.sqrt(R*R-r*r)
    ux, uy = -math.sin(d), math.cos(d)
    A = (T[0]-ux*h, T[1]-uy*h); Bp = (T[0]+ux*h, T[1]+uy*h)
    f.ln(*A, *Bp); f.dot(*O)
    f.t(A[0]-10, A[1]-14, "A"); f.t(Bp[0]+14, Bp[1]+8, "B"); f.t(O[0]-14, O[1]+16, "O")

